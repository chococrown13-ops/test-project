const BAD = ["씨발", "시발", "ㅅㅂ", "병신", "ㅄ", "좆", "개새", "새끼", "fuck", "shit", "섹스", "자살", "죽어", "엿먹", "꺼져", "닥쳐", "미친", "장애", "느금", "니애미", "애미", "애비", "보지", "자지", "일베", "한남", "김치녀", "틀딱"];
export function cleanText(s, max = 20) {
  s = String(s || "").replace(/\s+/g, " ").trim().slice(0, max);
  if (!s) return { ok: true, text: "" };
  const flat = s.toLowerCase().replace(/[\s._\-~!?*]+/g, "");
  if (BAD.some((w) => flat.includes(w))) return { ok: false, why: "고운 말로 다시 써 주세요." };
  if (/\d{3,}|https?:|www\.|@|\.com|\.kr|카톡|오픈채팅|텔레그램|인스타|디엠|dm/i.test(s)) return { ok: false, why: "연락처·주소·링크는 남길 수 없어요." };
  return { ok: true, text: s };
}
